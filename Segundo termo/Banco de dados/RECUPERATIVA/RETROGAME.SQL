DROP DATABASE RETROGAME_RECUPERATIVA_LEOBERTANHA;

CREATE DATABASE IF NOT EXISTS RETROGAME_RECUPERACAO_LEOBERTANHA;

USE RETROGAME_RECUPERACAO_LEOBERTANHA;

CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL UNIQUE,

    CONSTRAINT PK_ID_PLATAFORMA PRIMARY KEY (ID_PLATAFORMA)
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT,
    DESCRIÇÃO VARCHAR(120) NOT NULL UNIQUE,

    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA)
);

CREATE TABLE CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20) NULL,
    ATIVO BOOLEAN DEFAULT TRUE,

    CONSTRAINT PK_ID_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);

SELECT * FROM CLIENTE;

CREATE TABLE JOGOS (
    ID_JOGOS INT AUTO_INCREMENT,
    TITULO VARCHAR(120) NOT NULL,
    CODIGO VARCHAR(15) NOT NULL,
    ANO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK (QUANTIDADE_DISPONIVEL >= 0),
    ID_PLATAFORMA INT,
    ID_CATEGORIA INT,

    CONSTRAINT PK_ID_JOGOS PRIMARY KEY (ID_JOGOS),
    CONSTRAINT FK_ID_PLATAFORMA FOREIGN KEY (ID_PLATAFORMA) REFERENCES PLATAFORMA (ID_PLATAFORMA),
    CONSTRAINT FK_ID_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)
);

SELECT * FROM JOGOS;

CREATE TABLE LOCACAO (
    ID_LOCACAO INT AUTO_INCREMENT,
    DATA_RETIRADA DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NULL,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA' CHECK (STATUS_LOCACAO IN('ABERTA', 'DEVOLVIDO', 'ATRASADO')),
    ID_CLIENTE INT NOT NULL,
    ID_JOGOS INT NOT NULL,

    CONSTRAINT PK_ID_LOCACAO PRIMARY KEY (ID_LOCACAO),
    CONSTRAINT FK_ID_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES ID_CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_ID_JOGOS FOREIGN KEY (ID_JOGOS) REFERENCES ID_JOGOS (ID_JOGOS)
);

